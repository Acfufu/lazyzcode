import test from "node:test";
import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import { spawn, spawnSync } from "node:child_process";
import { once } from "node:events";
const script = fileURLToPath(new URL("../scripts/harvest-sandbox-usage.mjs", import.meta.url));
const hasSqlite = spawnSync("sqlite3", ["--version"], { encoding: "utf8", timeout: 5000 }).status === 0;

test("harvest CLI: real SQLite sources, preview is read-only, concurrent apply is idempotent and logs override", { skip: !hasSqlite && "sqlite3 CLI unavailable; real harvest source leg unverified" }, async t => {
  const dir = mkdtempSync(join(tmpdir(), "lzy-harvest-reliability-"));
  t.after(() => rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 }));
  const home = join(dir, "home"), project = join(dir, "project"), ledger = join(dir, "ledger");
  const hostPath = join(home, ".zcode", "cli", "db", "db.sqlite");
  const sourcePath = join(project, ".lazyzcode", "review", "same.a1.r1", "home", ".zcode", "cli", "db", "db.sqlite");
  for (const file of [hostPath, sourcePath]) mkdirSync(dirname(file), { recursive: true });
  const host = new DatabaseSync(hostPath);
  host.exec("CREATE TABLE session(directory TEXT)");
  host.prepare("INSERT INTO session VALUES(?)").run(project);
  host.close();
  const source = new DatabaseSync(sourcePath);
  source.exec("CREATE TABLE model_usage(provider_id TEXT, model_id TEXT, session_id TEXT, status TEXT, started_at INTEGER, completed_at INTEGER, input_tokens INTEGER, cache_read_input_tokens INTEGER, output_tokens INTEGER)");
  const at = Date.parse("2026-10-25T04:00:00Z");
  source.prepare("INSERT INTO model_usage VALUES(?,?,?,?,?,?,?,?,?)").run("fixture", "GLM-5.3-Flash", "s1", "completed", at, at + 1000, 1000, 0, 0);
  source.close();
  const env = { ...process.env, HOME: home, USERPROFILE: home, LZY_SANDBOX_USAGE_DIR: ledger, LZY_HARVEST_CUTOFF: "2026-10-01" };
  const preview = spawnSync(process.execPath, [script], { env, encoding: "utf8", timeout: 15000 });
  assert.equal(preview.status, 0, preview.stderr);
  assert.match(preview.stdout, /待追加 1/);
  assert.throws(() => readdirSync(ledger), { code: "ENOENT" });
  const apply = () => {
    const child = spawn(process.execPath, [script, "--apply"], { env, stdio: ["ignore", "pipe", "pipe"] });
    let out = "", err = "";
    child.stdout.on("data", b => out += b);
    child.stderr.on("data", b => err += b);
    const timer = setTimeout(() => child.kill("SIGKILL"), 15000);
    return once(child, "close").then(([code]) => { clearTimeout(timer); assert.equal(code, 0, err); assert.ok(out.includes(ledger)); return out; });
  };
  await Promise.all([apply(), apply()]);
  const path = join(ledger, readdirSync(ledger).find(n => n.endsWith(".jsonl")));
  const first = readFileSync(path, "utf8");
  assert.equal(first.trim().split("\n").length, 1);
  const db = new DatabaseSync(sourcePath);
  db.prepare("UPDATE model_usage SET input_tokens=1500,completed_at=?").run(at + 2000);
  db.close();
  await Promise.all([apply(), apply()]);
  const after = readFileSync(path, "utf8");
  assert.ok(after.startsWith(first));
  const rows = after.trim().split("\n").map(JSON.parse);
  assert.equal(rows.length, 2);
  assert.equal(rows.reduce((s, r) => s + r.usage[0].inputTokens, 0), 1500);
  assert.ok(rows.every(r => r.project === project));
  assert.deepEqual(rows[0].harvest.sessionIds, ["s1"]);
});
